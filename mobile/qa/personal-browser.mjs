import { nativeApp, installNativeFixture } from './mock-native.mjs';
import { chromium } from 'playwright';
import assert from 'node:assert/strict';

// All native APIs below are JS protocol fixtures, not Android / Firebase / sensors.
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,timezoneId:'Asia/Kolkata'});
const page=await context.newPage(); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await installNativeFixture(page,{steps:true,reminders:true});
const settings=()=>page.getByRole('button',{name:'Open settings'}).first();
const store=key=>page.evaluate(k=>JSON.parse(localStorage.getItem(k)||'null'),key);
const back=()=>page.evaluate(()=>window.__fitlifeHandleBack());
try {
  await page.goto(nativeApp,{waitUntil:'networkidle'}); await page.getByText("Today's overview").waitFor();
  await page.getByRole('button',{name:'Set up step tracking'}).click();
  let steps=page.getByRole('dialog',{name:'Your steps'}); await steps.waitFor();
  const phone=steps.locator('.step-source').filter({hasText:'Phone sensor'});
  const health=steps.locator('.step-source').filter({hasText:'Health Connect'});
  await phone.getByRole('button',{name:'Start'}).click();
  await phone.getByText('Tracking with a notification').waitFor();
  await health.getByRole('button',{name:'Connect'}).click(); await health.getByText('Connected',{exact:true}).waitFor();
  await steps.getByText('4,500',{exact:false}).first().waitFor();
  assert.equal(await steps.locator('.step-sheet-summary strong').innerText(),'4,500 steps','health and phone sources are not added');
  await steps.getByLabel('Daily goal').fill('7000'); await steps.getByRole('button',{name:'Save goal'}).click();
  assert.equal((await store('fitlife_settings_v2')).stepGoal,7000);
  await page.waitForFunction(()=>{const p=JSON.parse(localStorage.getItem('__fixture_cloud')||'{}')['qa-user']?.['c'.repeat(32)];return p && (JSON.parse(p).snapshot.settings.stepHistory||[]).length>=4;},null,{timeout:15000});
  let before=(await store('fitlife_settings_v2')).stepHistory;
  await steps.getByRole('button',{name:'Refresh step sources'}).click(); await page.waitForTimeout(400);
  let after=(await store('fitlife_settings_v2')).stepHistory;
  assert.deepEqual(after,before,'unchanged native readings do not dirty timestamps or cause uploads');
  await health.getByRole('button',{name:'Disconnect'}).click(); await health.getByText('Not connected').waitFor();
  await steps.getByText('6,200',{exact:false}).first().waitFor();
  assert.equal(await steps.locator('.step-sheet-summary strong').innerText(),'6,200 steps','phone fallback shown without summing');
  assert.equal(await back(),true); await steps.waitFor({state:'detached'});

  await page.getByRole('button',{name:'Workouts',exact:true}).click();
  await page.locator('.weekly-planner > summary').click();
  await page.getByRole('button',{name:/Mon/}).click();
  await page.getByLabel('Mon plan').selectOption('home-core');
  assert.equal((await store('fitlife_settings_v2')).weeklyPlan.find(x=>x.weekday===1).sessionId,'home-core');
  await page.getByLabel('Mon plan').selectOption('rest');
  assert.equal((await store('fitlife_settings_v2')).weeklyPlan.find(x=>x.weekday===1).sessionId,'rest');
  await page.locator('.guided-picker').getByRole('button',{name:'Start',exact:true}).click();
  let guide=page.getByRole('dialog',{name:'Home full body'}); await guide.waitFor();
  assert(await guide.getByText('Form cue').isVisible()); assert(await guide.getByText('Easier option').isVisible());
  await guide.locator('.guided-adjust > summary').click();
  await guide.getByLabel('Rest seconds').fill('0');
  const beforeSets=(await store('fitlife_workouts_v1')).length;
  await guide.getByRole('button',{name:'Log set'}).evaluate(button=>{button.click();button.click();});
  await page.waitForFunction(n=>JSON.parse(localStorage.getItem('fitlife_workouts_v1')||'[]').length===n+1,beforeSets);
  assert.equal((await store('fitlife_workouts_v1')).length,beforeSets+1,'double tap must not log twice');
  await guide.getByRole('button',{name:'Skip exercise'}).click();
  await guide.getByRole('button',{name:'Pause',exact:true}).click(); await guide.getByText('Workout paused').waitFor();
  assert.equal(await back(),true); await guide.waitFor({state:'detached'});
  await page.getByRole('button',{name:/Resume Home full body/}).click();
  guide=page.getByRole('dialog',{name:'Home full body'}); await guide.getByText('Workout paused').waitFor();
  await guide.getByRole('button',{name:'Resume workout'}).click();
  assert(await guide.getByText('Easier option').isVisible());
  await guide.getByRole('button',{name:'End session',exact:true}).click();
  assert(await guide.getByText('End this session? Logged sets will stay in your history.').isVisible());
  assert.equal(await back(),true); await guide.getByText('End this session? Logged sets will stay in your history.').waitFor({state:'hidden'});
  await guide.getByRole('button',{name:'End session',exact:true}).click(); await guide.getByRole('button',{name:'End session',exact:true}).last().click(); await guide.waitFor({state:'detached'});

  await page.getByRole('button',{name:'Meals',exact:true}).click();
  await page.getByLabel('Describe a meal').fill('2 boiled eggs'); await page.getByRole('button',{name:'Add (1)'}).click();
  const shortcut=page.locator('.meal-shortcut').filter({hasText:'Egg'}).first(); await shortcut.waitFor();
  const favorite=shortcut.getByRole('button',{name:/Add .* to favorite meals/}); await favorite.click();
  await page.getByRole('button',{name:'Favorites',exact:true}).click();
  const favoriteRow=page.locator('.meal-shortcut').first(); await favoriteRow.getByRole('button',{name:/Log .* again/}).click();
  const meal=page.getByRole('dialog',{name:'Log again'}); await meal.waitFor();
  const original=Number(await meal.getByLabel('Calories (kcal)').inputValue());
  await meal.getByLabel('Portion multiplier').fill('1.5');
  assert.equal(Number(await meal.getByLabel('Calories (kcal)').inputValue()),Math.round(original*1.5*10)/10,'portion scales proportionally');
  await meal.getByLabel('Calories (kcal)').fill('201.5');
  await meal.getByRole('button',{name:'Save nutrition details'}).click(); await meal.waitFor({state:'detached'});
  assert((await store('fitlife_meals_v1')).some(x=>x.calories===201.5),'reviewed manual nutrition is saved');
  await favoriteRow.getByRole('button',{name:/Remove .* from favorite meals/}).click();
  assert((await store('fitlife_settings_v2')).savedMeals.some(x=>x.deleted),'favorite removal is retained as a sync tombstone');

  await page.getByRole('button',{name:'Home',exact:true}).click(); await settings().click();
  await page.locator('.reminder-settings > summary').click();
  const reminder=page.locator('.reminder-settings');
  await reminder.getByLabel('Workout reminder time').fill('09:15');
  await reminder.locator('.reminder-row').filter({hasText:'Workout'}).getByRole('button',{name:'Turn on'}).click();
  assert.equal((await store('__fixture_reminders_qa-user')).workout.hour,9); assert.equal((await store('__fixture_reminders_qa-user')).workout.minute,15);
  await reminder.getByLabel('Workout reminder time').fill('10:30'); await reminder.getByRole('button',{name:'Save time'}).click();
  assert.equal((await store('__fixture_reminders_qa-user')).workout.hour,10);
  await reminder.locator('.reminder-row').filter({hasText:'Workout'}).getByRole('button',{name:'Turn off'}).click();
  assert.equal((await store('__fixture_reminders_qa-user')).workout.enabled,false);
  await page.getByRole('switch',{name:'Larger text'}).click();
  assert.equal(await page.getByRole('switch',{name:'Larger text'}).getAttribute('aria-checked'),'true');
  assert.equal(await page.evaluate(()=>getComputedStyle(document.documentElement).fontSize),'19.2px');
  for (const width of [320,390,768]) { await page.setViewportSize({width,height:844}); await page.waitForTimeout(100); assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`large text fits ${width}px`); }
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>localStorage.setItem('__fixture_offline','1'));
  await page.getByRole('button',{name:'Meals',exact:true}).click(); await page.getByLabel('Describe a meal').fill('1 banana'); await page.getByRole('button',{name:'Add (1)'}).click();
  await page.getByRole('button',{name:'Home',exact:true}).click(); await settings().click();
  await page.getByText('Changes on this device need sync').waitFor();
  await page.getByRole('button',{name:'Retry sync'}).click(); await page.getByText(/Cloud sync is offline/).waitFor();
  await page.evaluate(()=>localStorage.removeItem('__fixture_offline'));
  await page.getByRole('button',{name:'Retry sync'}).click(); await page.getByText('Up to date',{exact:true}).waitFor({timeout:15000});
  assert(await page.getByText(/Last successful sync:/).isVisible());
  await page.locator('.settings-fold > summary').filter({hasText:'Encrypted backup'}).click();
  assert(await page.getByRole('button',{name:'Create backup'}).isVisible());
  // An old account's delayed sensor response must neither block a new account
  // nor be applied to its partition after an A → B switch.
  const reads=Number(await page.evaluate(()=>localStorage.getItem('__fixture_step_reads_qa-user')||0));
  await page.evaluate(()=>{localStorage.setItem('__fixture_steps_delay','4000');document.dispatchEvent(new Event('visibilitychange'));});
  await page.waitForFunction(n=>Number(localStorage.getItem('__fixture_step_reads_qa-user')||0)>n,reads);
  await page.evaluate(()=>localStorage.removeItem('__fixture_steps_delay'));
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.getByRole('button',{name:'Sign in with Google',exact:true}).waitFor();
  await page.evaluate(()=>localStorage.setItem('__fixture_next','other-account'));
  await page.getByRole('button',{name:'Sign in with Google',exact:true}).click();
  await page.waitForFunction(()=>Number(localStorage.getItem('__fixture_step_reads_other-account')||0)>0,null,{timeout:2500});
  await page.waitForTimeout(4200);
  assert.equal(((await store('fitlife_cloud_partition_v1:other-account')).snapshot.settings.stepHistory||[]).length,0,'delayed prior-account steps do not leak');
  assert.equal((await store('__fixture_reminders_other-account')),null,'new account does not inherit reminder preferences');
  assert.deepEqual(errors,[]);
  console.log('PASS: simulated step source choices, synced observations, guided logging/pause/Back, plans, favorites, meal scaling, local reminder protocol, large text and sync recovery.');
} finally { await context.close(); await browser.close(); }
