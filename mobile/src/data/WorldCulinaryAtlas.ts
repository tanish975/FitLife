import type {
  EdibleCategoryId,
  FoodAllergenFlag,
  FoodDietaryFlag,
  FoodEdibleState,
  FoodItem,
  FoodMeasuredPortion,
  FoodMicronutrients,
  FoodPreparationProfile,
  MealCategory,
  WorldRegionId,
} from './types';

interface WorldDishSeed {
  id: string;
  name: string;
  servingLabel: string;
  servingGrams: number;
  calories: number;
  proteinG: number;
  carbsG: number;
  fatG: number;
  fiberG: number;
  sugarG?: number;
  sodiumMg?: number;
  defaultCategory: MealCategory;
  worldRegion: WorldRegionId;
  countryCodes: string[];
  originLabel: string;
  edibleCategory?: EdibleCategoryId;
  edibleState?: FoodEdibleState;
  preparationProfile?: FoodPreparationProfile;
  scientificName?: string;
  aliases: string[];
  dietaryFlags: FoodDietaryFlag[];
  allergenFlags?: FoodAllergenFlag[];
  measuredPortions?: FoodMeasuredPortion[];
  micronutrients?: FoodMicronutrients;
  provenanceNote: string;
}

function makeWorldDish(seed: WorldDishSeed): FoodItem {
  const tags = [
    'global-atlas',
    seed.worldRegion,
    ...seed.countryCodes.map((c) => c.toLowerCase()),
    ...seed.dietaryFlags,
  ];
  return {
    id: seed.id,
    name: seed.name,
    servingLabel: seed.servingLabel,
    calories: seed.calories,
    proteinG: seed.proteinG,
    carbsG: seed.carbsG,
    fatG: seed.fatG,
    fiberG: seed.fiberG,
    defaultCategory: seed.defaultCategory,
    tags,
    source: 'fitlife-global-dish',
    sourceCode: `ATLAS ${seed.countryCodes[0]}`,
    cuisineTag: 'global',
    worldRegion: seed.worldRegion,
    countryCodes: seed.countryCodes,
    originLabel: seed.originLabel,
    edibleCategory: seed.edibleCategory ?? 'prepared-dishes',
    edibleState: seed.edibleState ?? 'cooked',
    dietaryFlags: seed.dietaryFlags,
    ...(seed.allergenFlags && seed.allergenFlags.length ? { allergenFlags: seed.allergenFlags } : {}),
    ...(seed.measuredPortions && seed.measuredPortions.length
      ? { measuredPortions: seed.measuredPortions }
      : {}),
    ...(seed.micronutrients ? { micronutrients: seed.micronutrients } : {}),
    ...(seed.scientificName ? { scientificName: seed.scientificName } : {}),
    aliases: seed.aliases,
    servingGrams: seed.servingGrams,
    ...(seed.sugarG !== undefined ? { sugarG: seed.sugarG } : {}),
    ...(seed.sodiumMg !== undefined ? { sodiumMg: seed.sodiumMg } : {}),
    preparationProfile: seed.preparationProfile ?? 'cooked_dish',
    isRaw: seed.edibleState === 'raw',
    provenanceNote: seed.provenanceNote,
  };
}

